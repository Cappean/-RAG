import { expect, test } from '@playwright/test'

/** This test writes only clearly marked technical verification resources. Never mocks API. */
test('real UI patient, MD ingestion, streaming turns, reload and source line location', async ({ page }, testInfo) => {
  const marker = `UI技术验证-${Date.now()}`
  const documentName = `${marker}.md`
  const original = `# ${marker}：知识链路技术验收记录\n\n本记录仅用于软件技术验收，不包含真实患者资料，不构成医疗建议。\n\n## 校验口令\n\n${marker} 的校验口令固定为“青松七号”。校验口令用于确认知识检索命中了这份技术验收记录。\n\n## 验收步骤\n\n第一步上传原始 Markdown 文件，第二步解析并向量入库，第三步开展两轮流式问答，第四步刷新页面检查历史仍在，第五步打开原文核对行号。\n\n## 原文定位\n\n${marker} 的原文定位必须使用这份未修改 Markdown 文件的物理行号；不得使用生成摘要替代原文。\n`
  const browserErrors: string[] = []
  page.on('pageerror', error => browserErrors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('正在加载真实数据…')).not.toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: '新增档案' }).click()
  await page.getByLabel('姓名或称呼').fill(marker)
  await page.getByRole('button', { name: '保存档案', exact: true }).click()
  await expect(page.getByRole('heading', { name: '新增患者档案' })).not.toBeVisible()
  await expect(page.getByLabel('选择患者')).toHaveValue(/^[a-f0-9]{24}$/)
  const patientId = await page.getByLabel('选择患者').inputValue()
  await page.getByRole('button', { name: '编辑档案' }).click()
  await page.getByLabel('当前用药（每行一项）').fill('未填写；仅为软件技术验证占位说明')
  await page.getByRole('button', { name: '保存档案', exact: true }).click()
  await expect(page.getByText('当前用药：未填写；仅为软件技术验证占位说明')).toBeVisible()

  const uploadResponse = page.waitForResponse(response => response.url().endsWith('/api/knowledge/documents') && response.request().method() === 'POST')
  await page.locator('input[type=file]').setInputFiles({ name: documentName, mimeType: 'text/markdown', buffer: Buffer.from(original, 'utf8') })
  const upload = await (await uploadResponse).json()
  expect(upload.document.id).toMatch(/^[a-f0-9]{24}$/)
  expect(upload.taskId).toBeTruthy()
  const documentRow = page.locator('.document-row').filter({ hasText: documentName })
  await expect(documentRow.locator('.doc-status')).toHaveText('可检索', { timeout: 300_000 })
  await expect(page.getByText(`任务 ${String(upload.taskId).slice(0, 8)}：完成`)).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('01-document-ready.png'), fullPage: true })
  await documentRow.getByRole('button', { name: '查看原文' }).click()
  await expect(page.locator('.markdown-original code').first()).toContainText(marker, { timeout: 30_000 })
  expect((await page.locator('.markdown-original code').allTextContents()).join('\n')).toBe(original)
  await expect(page.locator('.viewer-source-note')).toContainText('没有可用行号')
  await page.screenshot({ path: testInfo.outputPath('01b-original-file-no-fabricated-location.png'), fullPage: true })
  await page.getByRole('button', { name: '关闭原文' }).click()

  await page.getByRole('button', { name: '新建智能问诊' }).click()
  await expect(page.locator('.history-item.selected')).toHaveCount(1)
  const composer = page.locator('.composer textarea')
  await composer.fill(`请根据《${marker}：知识链路技术验收记录》回答：${marker} 的校验口令是什么？请引用原文。此问题只用于软件技术验收。`)
  await page.getByRole('button', { name: '发送问诊', exact: true }).click()
  await expect(page.getByRole('button', { name: '生成中…', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '生成中…', exact: true })).not.toBeVisible({ timeout: 240_000 })
  await expect(page.locator('.message-card.assistant')).toHaveCount(1)
  await expect(page.locator('.message-card.assistant .message-heading')).toContainText('已保存')
  const citation = page.locator('.message-card.assistant .evidence-card').filter({ hasText: documentName }).first()
  await expect(citation).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('02-first-answer.png'), fullPage: true })

  await composer.fill(`继续上一轮：${marker} 记录中，刷新后应检查什么？请基于同一技术验收记录并引用原文。`)
  await page.getByRole('button', { name: '发送问诊', exact: true }).click()
  await expect(page.getByRole('button', { name: '生成中…', exact: true })).not.toBeVisible({ timeout: 240_000 })
  await expect(page.locator('.message-card')).toHaveCount(4)
  const conversationId = await page.evaluate(() => localStorage.getItem('medical.demo.conversation'))
  const before = await page.locator('.message-card .message-content').allTextContents()
  await page.reload()
  await expect(page.locator('.message-card')).toHaveCount(4, { timeout: 30_000 })
  expect(await page.locator('.message-card .message-content').allTextContents()).toEqual(before)
  await expect(page.getByLabel('选择患者')).toHaveValue(patientId)
  await page.screenshot({ path: testInfo.outputPath('03-reloaded-history.png'), fullPage: true })

  await page.locator('.message-card.assistant .evidence-card').filter({ hasText: documentName }).first().click()
  await expect(page.getByRole('dialog', { name: '引用原文' })).toBeVisible()
  await expect(page.locator('.markdown-original .line-highlight').first()).toBeVisible({ timeout: 30_000 })
  await expect(page.locator('.viewer-source-note')).toContainText('已定位并高亮原文行号')
  const originalDom = await page.locator('.markdown-original code').allTextContents()
  expect(originalDom.join('\n')).toBe(original)
  const highlights = await page.locator('.markdown-original .line-highlight').evaluateAll(elements => elements.map(element => ({ line: element.getAttribute('data-line'), text: element.textContent })))
  await page.screenshot({ path: testInfo.outputPath('04-markdown-location.png'), fullPage: true })
  await testInfo.attach('technical-verification-evidence', { body: JSON.stringify({ marker, patientId, documentId: upload.document.id, taskId: upload.taskId, conversationId, messageCount: 4, originalPreserved: true, highlights, browserErrors }, null, 2), contentType: 'application/json' })
  expect(browserErrors).toEqual([])
})
